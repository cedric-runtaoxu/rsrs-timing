def md(frame,percent=(),decimals=3):
    def fmt(col,v):
        if pd.isna(v):return '—'
        if col in percent:return f'{v:.2%}'
        if isinstance(v,(float,np.floating)):return f'{v:.{decimals}f}'
        return str(v).replace('|','／')
    return '\n'.join(['| '+' | '.join(map(str,frame.columns))+' |',
                       '| '+' | '.join(['---']*len(frame.columns))+' |']+
                      ['| '+' | '.join(fmt(k,v) for k,v in row.items())+' |' for _,row in frame.iterrows()])


def table_md(table):
    if '统计量' not in table:return md(table)
    q=table.astype(object).copy()
    for i,row in q.iterrows():
        name=row['统计量']
        rate=('率' in name or '回撤' in name or '最大盈利' in name or '最大亏损' in name) and '比率' not in name
        for col in q.columns[1:]:
            v=row[col]
            q.loc[i,col]='—' if pd.isna(v) else f'{v:.2%}' if rate else f'{v:.2f}'
    return md(q)


