"""将原报告期的检验结果写成可独立阅读的解释；数值均来自结果表。"""
from .research_spec import LONG_STRATEGIES, SHORT_STRATEGIES


def explain_indicators(frames, markdown):
    p=frames['predictive']
    q=p[(p['市场']=='沪深300')&(p['分期']=='原报告期')&
        (p['预测天数']==10)&(p['HAC阶数']==20)]
    labels={'beta':'斜率β（N=18）','zscore':'标准分（18,600）',
            'modified':'修正标准分（18,600）','right_skewed':'右偏标准分（18,600）',
            'right_skewed_16_300':'基础右偏（16,300，另列参数）'}
    a=q[q['标签起点延迟']==0].set_index('指标')
    d=q[q['标签起点延迟']==1].set_index('指标')
    table=a.loc[list(labels),['Pearson']].rename(columns={'Pearson':'与未来10日收益的相关性'})
    table['延迟到次日收盘后的相关性']=d.loc[list(labels),'Pearson']
    table.insert(0,'指标',[labels[x] for x in table.index])
    r=a.loc['right_skewed'];aligned=d.loc['right_skewed']
    bins=frames['fixed_bins']
    bins=bins[(bins['市场']=='沪深300')&(bins['分期']=='原报告期')&
              (bins['指标']=='right_skewed')].sort_values('组').copy()
    bins['指标从低到高的分组']=['第1组：最低','第2组','第3组','第4组','第5组：最高']
    low,high=bins.iloc[0],bins.iloc[-1]
    return [
        '### 4.1 先明确“指标有效”是什么意思',
        '这里先看沪深300在2005-04-08—2017-04-28的结果。指标有效，指它的高低与之后市场表现存在有用关系。例如指标较高时，未来10日的平均收益是否更高。这个问题暂时不涉及怎么买卖，也不要求每天都预测正确。',
        '**我们的判断：原报告期内，RSRS包含一定的正向预测信息，但关系强度有限，统计证据需要保留条件。** 不能直接把它概括成“已经证明可以稳定预测行情”。',
        '### 4.2 每天的指标，是否与之后的收益有关',
        '做法是把每个交易日的指标值与随后10个交易日的收益配对，再看两者是否同方向变化。表里的相关系数在−1到1之间：正数表示指标越高时，未来收益总体倾向越高；接近0表示线性关系弱。相关系数不是胜率，也不是策略收益率。',
        markdown(table.reset_index(drop=True),{k:'{:.3f}' for k in table.columns if k!='指标'}),
        f"四个同参数口径中的相关性都为正。右偏(18,600)为{r.Pearson:.3f}，高于标准分的{a.loc['zscore','Pearson']:.3f}，说明这项10日线性相关检验支持修正、右偏变换相对标准分的改善。不过，{r.Pearson:.3f}仍是有限强度的关系，不能读成“有{r.Pearson:.1%}的胜率”。",
        f"考虑实际交易需要等到次日收盘，右偏相关性仍为{aligned.Pearson:.3f}，没有因为推迟起算就消失。这为它含有一定可利用的信息提供了支持。这里对齐的是收益起点，尚未计算完整交易策略和费用。",
        f"也不能说四个指标越改越好：原始斜率的相关性{a.loc['beta','Pearson']:.3f}高于标准分；按只比较排序的Spearman相关性，原始斜率为{a.loc['beta','Spearman']:.3f}，右偏(18,600)为{r.Spearman:.3f}。右偏(16,300)又有不同结果。因此优势取决于评价方法和参数，不能预设右偏在所有意义上最好。",
        '### 4.3 把指标分组后，差别有多大',
        '另一种直观读法是：按右偏(18,600)指标从低到高分为五组，再看每组信号之后10日的平均收益。这里的收益是指数未来收益，不是持有某一组就能直接得到的交易策略收益。',
        markdown(bins[['指标从低到高的分组','样本数','未来10日均值']].rename(
            columns={'未来10日均值':'随后10日平均收益'}),{'随后10日平均收益':'{:.2%}'}),
        f"最高组的随后10日平均收益为{high['未来10日均值']:.2%}，最低组为{low['未来10日均值']:.2%}，相差{(high['未来10日均值']-low['未来10日均值'])*100:.2f}个百分点。两端分组的差异支持指标具有一定区分能力。",
        '但中间三组并没有随指标升高而依次上升，所以不能说“指标越高，收益就一定越高”。这些10日收益还有重叠，分组图也使用同一历史样本，因此这张表是直观证据，不是独立的新实验。',
        '### 4.4 为什么看到正相关，还不能下很强的结论',
        '第一，连续两天各自向后看10天，收益区间有9天重叠，不能把它们当成完全独立的观测。我们用HAC方法调整统计不确定性，避免把证据说得过强。',
        f"第二，如果单独看右偏(18,600)的这一个10日检验，调整后的原始p值约为{r['HAC_p探索']:.4g}，低于常用的0.05门槛；但本研究同时检查了多个市场、指标、期限和起算方式。为减少“试得多，总能碰到一个显著结果”的问题，对同一分期120项主检验进行Holm校正后，p值为{r['HAC_p_Holm']:.3f}，超过0.05。执行对齐版本校正后为{aligned['HAC_p_Holm']:.3f}。",
        'p值用于衡量数据在特定统计假设下提供的证据，不是“指标无效的概率”。校正后未过门槛，也不等于证明指标没有作用；它意味着本研究不能以同样强度宣称这一关系已通过全部多重检验要求。',
        '**因此，指标层面的准确结论是：在原报告期内，我们观察到方向合理的正相关与高低分组差异，支持其具有一定历史预测信息；但尚不足以认定这种信息很强、普遍存在或一定持续。**',
    ]


def explain_strategies(frames, markdown):
    m=frames['metrics']
    q=m[(m['市场']=='沪深300')&(m['分期']=='原报告期')].set_index('策略')
    pct={'年化收益':'{:.2%}','最大回撤':'{:.2%}','平均绝对仓位':'{:.2%}','夏普':'{:.2f}'}
    def table(names):
        return markdown(q.loc[names,['年化收益','夏普','最大回撤','平均绝对仓位']].reset_index(),pct)
    basic=['斜率','标准分','修正标准分','右偏(16,300)']
    filtered=[name for name in LONG_STRATEGIES if name not in basic]
    bench=q.loc['买入持有'];unfiltered=q.loc['右偏(18,600)']
    price=q.loc['价格过滤·右偏'];vol=q.loc['量过滤·右偏'];short=q.loc['多空·价格过滤·右偏']
    return [
        '### 5.1 策略有效，要看能否把信号变成收益',
        '指标只有一个数值；策略还要规定何时开仓、何时退出、是否过滤、能否做空，以及何时成交和如何收费。我们将这些规则固定后运行历史回测，并与同期间买入持有比较。以下全部是沪深300，2005-04-08—2017-04-28，次日收盘执行、单边费用0.1%的结果。',
        '**我们的判断：原报告期内，这些RSRS策略取得了较好的样本内回测效果，尤其过滤版多头在收益与回撤的组合上表现较好。** 这比“指标与未来收益正相关”多了一层交易验证，但仍属于历史构建区间内的证据。',
        '先读懂三个数字：**年化收益**把整个期间的复合增长换算成年均水平，不代表每年都赚这么多；**最大回撤**表示资金从此前高点最多跌了多少，−50%意味着一度腰斩；**夏普**衡量平均收益相对于日常波动的大小，在相同口径下通常越高越好。',
        '平均绝对仓位表示实际承担市场收益的比例。在0/1多头策略中，它约等于持有指数的天数占比；它可以帮助判断回撤降低是否同时伴随更少的市场参与。',
        '### 5.2 不加量价过滤，四个基础策略有没有效果',
        table(['买入持有']+basic),
        f"四个基础策略的年化收益约为{q.loc[basic,'年化收益'].min():.2%}—{q.loc[basic,'年化收益'].max():.2%}，都高于买入持有的{bench['年化收益']:.2%}；夏普也都高于基准。这支持“把RSRS按阈值转换为买卖规则，在原报告期有较好的回测表现”。",
        '不过，基础策略仍出现约45%—57%的最大回撤。它们虽然比买入持有的回撤小，资金曲线仍然会经历很大的损失。因此，收益提高不等于风险已经得到充分控制。',
        '### 5.3 原文的价格、成交量过滤带来了什么',
        '先固定指标参数进行比较。基础右偏原本用(16,300)，过滤版用(18,600)，直接拿两者相减会混入参数变化；因此这里另加无过滤右偏(18,600)作对照。',
        table(['右偏(18,600)','价格过滤·右偏','量过滤·右偏']),
        f"同为右偏(18,600)，无过滤的年化收益为{unfiltered['年化收益']:.2%}、最大回撤{unfiltered['最大回撤']:.2%}；价格过滤后为{price['年化收益']:.2%}、{price['最大回撤']:.2%}；成交量过滤后为{vol['年化收益']:.2%}、{vol['最大回撤']:.2%}。在这个期间，过滤不仅减少了回撤，还提高了收益。",
        f"价格过滤版实际持仓约占{price['平均绝对仓位']:.2%}的交易日，低于无过滤版的{unfiltered['平均绝对仓位']:.2%}。这说明它在样本中用较少的持仓取得了较好表现。但回撤下降也包含市场暴露减少的贡献，不能全部归功于更准确的预测。",
        '六个多头过滤组合的完整结果如下，避免只展示右偏版本：',
        table(filtered),
        f"其中价格过滤修正标准分的年化收益为{q.loc['价格过滤·修正','年化收益']:.2%}、夏普为{q.loc['价格过滤·修正','夏普']:.2f}，在这六个组合中高于价格过滤右偏。因此，我们复现支持量价过滤在该样本内有价值，但不支持“右偏版本必然是最优版本”。",
        '### 5.4 这些效果是否只是普通趋势择时也能做到',
        table(['买入持有','MA20','BOLL(14,2)','价格过滤·右偏']),
        'MA20和布林带在这个时期同样有较好表现，说明这个历史区间本身也有利于一些趋势择时规则。价格过滤右偏的收益、夏普和回撤表现优于表内这两个技术基线，但我们没有据此宣称它拥有统计上已经确认的独有优势。',
        '### 5.5 加上做空，是否更好',
        table(['价格过滤·右偏','多空·价格过滤·右偏','量过滤·右偏','多空·量过滤·右偏']),
        f"价格过滤右偏从多头扩展到多空，年化收益由{price['年化收益']:.2%}提高至{short['年化收益']:.2%}，但最大回撤从{price['最大回撤']:.2%}扩大到{short['最大回撤']:.2%}，夏普也从{price['夏普']:.2f}降至{short['夏普']:.2f}。",
        '所以做空带来了更高的这段历史总收益，同时也承担了更多波动和更深回撤。不能只看年化收益就判断多空版全面更好；成交量过滤版同样体现了这种取舍。六种多空组合的完整结果见研究报告。',
        '这些多空数值只扣了统一交易费，主表没有计入真实借券、股息补偿、基差和保证金约束，因此这里判断的是指数模拟规则的历史效果。',
        '### 5.6 原报告期，我们究竟证明到了哪一步',
        '**指标层面：有一定正向预测信息的历史证据，但信号强度有限，多重检验后的统计把握不足以支持强结论。策略层面：在这段历史和统一账户模型下，RSRS策略确实取得了优于买入持有的回测表现；量价过滤版改善明显，做空则体现收益与风险的取舍。**',
        '这两项结论可以同时成立。逐日相关性检验评价所有信号高低与固定10日收益的关系；策略则按阈值筛选部分时段，并依据后续信号决定持有多久，考察的是不同问题。较低的相关性不排除某种交易规则在样本内赚钱，而漂亮的策略回测也不能反过来证明每项预测检验都显著。',
        '研报的指标、参数和策略本来就是在发表前历史中形成的。因此原报告期的复现回答的是“这段历史中能否得到支持”，不能把它当作独立的未来验证。接下来保持规则完全不变，延长至发表后的数据，才是在检验这种表现是否持续。',
    ]
